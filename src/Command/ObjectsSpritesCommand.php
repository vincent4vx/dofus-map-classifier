<?php

declare(strict_types=1);

namespace MapClassifier\Command;

use JsonException;
use MapClassifier\Config;
use MapClassifier\Objects\SpriteSet;
use MapClassifier\Objects\SpriteSvgExporter;
use Override;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Input\InputOption;
use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\Console\Style\SymfonyStyle;

use function count;
use function file_get_contents;
use function is_array;
use function is_file;
use function json_decode;
use function sprintf;

use const JSON_THROW_ON_ERROR;

#[AsCommand('objects:sprites', 'Export the ground and object sprites to SVG files')]
final class ObjectsSpritesCommand extends Command
{
    public function __construct(
        private readonly SpriteSvgExporter $exporter,
        private readonly Config $config,
    ) {
        parent::__construct();
    }

    #[Override]
    protected function configure(): void
    {
        $this
            ->addOption('objects', null, InputOption::VALUE_REQUIRED, 'Objects file generated by objects:analyze: only used sprites are exported', $this->config->varDir . '/objects.json')
            ->addOption('all', 'a', InputOption::VALUE_NONE, 'Export all sprites of the client, even unused ones')
            ->addOption('force', 'f', InputOption::VALUE_NONE, 'Export again already exported sprites')
        ;
    }

    #[Override]
    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $io = new SymfonyStyle($input, $output);
        $used = null;

        if (!$input->getOption('all')) {
            $file = (string) $input->getOption('objects');

            if (!is_file($file)) {
                $io->error($file . ' not found: run objects:analyze first, or use --all');

                return self::FAILURE;
            }

            try {
                $used = json_decode((string) file_get_contents($file), true, flags: JSON_THROW_ON_ERROR);
            } catch (JsonException $e) {
                $io->error('Invalid ' . $file . ': ' . $e->getMessage());

                return self::FAILURE;
            }
        }

        $dir = $this->config->varDir . '/sprites';

        foreach (SpriteSet::cases() as $set) {
            $only = $used === null ? null : (is_array($used[$set->value] ?? null) ? $used[$set->value] : []);
            $progress = $io->createProgressBar($only !== null ? count($only) : 0);
            $progress->setFormat(' ' . $set->value . ' %current%/%max% [%bar%] %elapsed:6s%');

            $report = $this->exporter->export(
                $set,
                $dir,
                $only,
                (bool) $input->getOption('force'),
                static fn () => $progress->advance(),
            );

            $progress->finish();
            $io->newLine();
            $io->text(sprintf('%s: %d exported, %d already exported, %d failed', $set->value, $report['exported'], $report['skipped'], count($report['failed'])));

            if ($output->isVerbose()) {
                foreach ($report['failed'] as $id => $error) {
                    $io->text(sprintf('  <comment>%d: %s</comment>', $id, $error));
                }
            }
        }

        $io->success('Sprites exported to ' . $dir);

        return self::SUCCESS;
    }
}
