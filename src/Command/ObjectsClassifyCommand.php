<?php

declare(strict_types=1);

namespace MapClassifier\Command;

use InvalidArgumentException;
use JsonException;
use MapClassifier\Kernel;
use MapClassifier\Objects\Layer;
use MapClassifier\Objects\ObjectProfile;
use MapClassifier\Objects\SpriteSet;
use MapClassifier\ObjectType\ObjectTypeResult;
use MapClassifier\Storage\ResultStorage;
use Override;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputArgument;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Input\InputOption;
use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\Console\Style\SymfonyStyle;

use function array_slice;
use function count;
use function file_get_contents;
use function file_put_contents;
use function is_array;
use function is_file;
use function json_decode;
use function max;
use function preg_match;
use function sprintf;
use function usort;

use const JSON_THROW_ON_ERROR;

#[AsCommand('objects:classify', 'Find the type of sprites (category, name, keywords) using the OpenAI Responses API')]
final class ObjectsClassifyCommand extends Command
{
    public function __construct(
        private readonly Kernel $kernel,
    ) {
        parent::__construct();
    }

    #[Override]
    protected function configure(): void
    {
        $this
            ->addArgument('ids', InputArgument::IS_ARRAY, 'Sprite ids or ranges, prefixed by "g" for grounds or "o" for objects (e.g. o345 g10-20). Without prefix, both sets are selected')
            ->addOption('set', null, InputOption::VALUE_REQUIRED, 'Only this sprite set (grounds or objects)')
            ->addOption('layer', null, InputOption::VALUE_REQUIRED, 'Only sprites mainly used on this layer (background, ground, layer1, layer2)')
            ->addOption('interactive', null, InputOption::VALUE_NONE, 'Only sprites of interactive objects (resources, workshops…)')
            ->addOption('min-maps', null, InputOption::VALUE_REQUIRED, 'Only sprites used on at least this number of maps', '1')
            ->addOption('limit', 'l', InputOption::VALUE_REQUIRED, 'Maximum number of sprites to classify (most used first)')
            ->addOption('concurrency', 'c', InputOption::VALUE_REQUIRED, 'Number of parallel requests', '10')
            ->addOption('retry-errors', null, InputOption::VALUE_NONE, 'Classify again sprites with an error')
            ->addOption('force', 'f', InputOption::VALUE_NONE, 'Classify again already classified sprites')
            ->addOption('objects', null, InputOption::VALUE_REQUIRED, 'Objects file generated by objects:analyze', $this->kernel->config->varDir . '/objects.json')
        ;
    }

    #[Override]
    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $io = new SymfonyStyle($input, $output);
        $file = (string) $input->getOption('objects');

        if (!is_file($file)) {
            $io->error($file . ' not found: run objects:analyze and objects:sprites first');

            return self::FAILURE;
        }

        try {
            $data = json_decode((string) file_get_contents($file), true, flags: JSON_THROW_ON_ERROR);
        } catch (JsonException $e) {
            $io->error('Invalid ' . $file . ': ' . $e->getMessage());

            return self::FAILURE;
        }

        $ranges = self::parseIds($input->getArgument('ids'));
        $set = $input->getOption('set') !== null ? SpriteSet::from((string) $input->getOption('set')) : null;
        $layer = $input->getOption('layer') !== null ? Layer::from((string) $input->getOption('layer')) : null;
        $minMaps = (int) $input->getOption('min-maps');
        $interactiveOnly = (bool) $input->getOption('interactive');
        $force = (bool) $input->getOption('force');
        $retry = (bool) $input->getOption('retry-errors');
        $storage = $this->kernel->objectTypes;
        $classifier = $this->kernel->objectTypeClassifier();
        $todo = [];
        $missingSprites = 0;

        foreach (SpriteSet::cases() as $spriteSet) {
            if ($set !== null && $set !== $spriteSet) {
                continue;
            }

            foreach (is_array($data[$spriteSet->value] ?? null) ? $data[$spriteSet->value] : [] as $profileData) {
                $profile = ObjectProfile::fromArray($spriteSet, $profileData);

                if (
                    ($layer !== null && $profile->layer !== $layer)
                    || ($interactiveOnly && $profile->interactive === null)
                    || $profile->maps < $minMaps
                    || !self::matches($ranges, $profile)
                ) {
                    continue;
                }

                $result = $storage->get($profile->set, $profile->id);

                if ($result !== null && !$force && ($result->ok || !$retry)) {
                    continue;
                }

                if (!$classifier->hasSprite($profile)) {
                    ++$missingSprites;
                    continue;
                }

                $todo[] = $profile;
            }
        }

        if ($missingSprites) {
            $io->warning(sprintf('%d sprites ignored: image not exported (run objects:sprites)', $missingSprites));
        }

        // Most used sprites first
        usort($todo, static fn (ObjectProfile $a, ObjectProfile $b) => $b->maps <=> $a->maps ?: $a->id <=> $b->id);

        if (($limit = $input->getOption('limit')) !== null) {
            $todo = array_slice($todo, 0, (int) $limit);
        }

        if (!$todo) {
            $io->success('Nothing to classify');

            return self::SUCCESS;
        }

        $io->text(sprintf('Classifying %d sprites (model: %s)', count($todo), $this->kernel->config->openAiModel));

        $ok = 0;
        $errors = 0;
        $progress = $io->createProgressBar(count($todo));
        $progress->setFormat(' %current%/%max% [%bar%] %percent:3s%% %elapsed:6s%/%estimated:-6s% %message%');
        $progress->setMessage('');
        $progress->start();

        $classifier->classify($todo, max(1, (int) $input->getOption('concurrency')), static function (ObjectTypeResult $result) use ($io, $output, $progress, &$ok, &$errors) {
            $prefix = $result->set === SpriteSet::Grounds ? 'g' : 'o';

            if ($result->ok) {
                ++$ok;
                $message = sprintf('%s%d: %s (%s)', $prefix, $result->id, $result->classification->name, $result->classification->category->value);
            } else {
                ++$errors;
                $message = sprintf('<comment>%s%d: %s</comment>', $prefix, $result->id, $result->error);
            }

            if ($output->isVerbose() || !$result->ok) {
                $progress->clear();
                $io->writeln($message);
                $progress->display();
            }

            $progress->setMessage($prefix . $result->id);
            $progress->advance();
        });

        $progress->finish();
        $io->newLine(2);

        $this->joinTypes($data, $file);
        $io->text('Types joined in ' . $file);

        $errors
            ? $io->warning(sprintf('%d sprites classified, %d errors', $ok, $errors))
            : $io->success(sprintf('%d sprites classified', $ok));

        return self::SUCCESS;
    }

    /**
     * Update the "type" field of the objects file, so objects:analyze does not need to be run again
     *
     * @param array<array-key, mixed> $data Decoded objects file
     */
    private function joinTypes(array $data, string $file): void
    {
        foreach (SpriteSet::cases() as $set) {
            if (!is_array($data[$set->value] ?? null)) {
                continue;
            }

            $types = $this->kernel->objectTypes->all($set);
            $profiles = [];

            foreach ($data[$set->value] as $id => $profile) {
                $profile['type'] = ObjectProfile::fromArray($set, $profile)->type(($types[(int) $id] ?? null)?->classification)?->toArray();
                $profiles[$id] = $profile;
            }

            // Keep sprites indexed by id (JSON object) even if ids are sequential
            $data[$set->value] = (object) $profiles;
        }

        file_put_contents($file, ResultStorage::encode($data) . "\n");
    }

    /**
     * @param list<string> $arguments
     * @return list<array{SpriteSet|null, int, int}>
     */
    private static function parseIds(array $arguments): array
    {
        $ranges = [];

        foreach ($arguments as $argument) {
            if (!preg_match('/^([go]?)(\d+)(?:-(\d+))?$/', $argument, $m)) {
                throw new InvalidArgumentException('Invalid sprite id or range "' . $argument . '" (expected e.g. "o345", "g10-20" or "345")');
            }

            $ranges[] = [
                match ($m[1]) {
                    'g' => SpriteSet::Grounds,
                    'o' => SpriteSet::Objects,
                    default => null,
                },
                (int) $m[2],
                isset($m[3]) ? (int) $m[3] : (int) $m[2],
            ];
        }

        return $ranges;
    }

    /**
     * @param list<array{SpriteSet|null, int, int}> $ranges
     */
    private static function matches(array $ranges, ObjectProfile $profile): bool
    {
        if (!$ranges) {
            return true;
        }

        foreach ($ranges as [$set, $min, $max]) {
            if (($set === null || $set === $profile->set) && $profile->id >= $min && $profile->id <= $max) {
                return true;
            }
        }

        return false;
    }
}
